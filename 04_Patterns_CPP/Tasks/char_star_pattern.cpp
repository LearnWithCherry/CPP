#include<iostream>
using namespace std;

int main(){
    int n = 5;//---------------------------------------------------------- define how many lines to print 
    char ch = 'A';//---------------------------------------------------------- what to print 

    for(int i=1; i<n; i++){//---------------------------------------------------------- outer loop 
        for(int j=1; j<n; j++){//---------------------------------------------------------- Inner loop
            cout << ch << " ";//---------------------------------------------------------- print character 
            //ch++;//---------------------------------------------------------- if you want to increase numbers from 1 to n!
        }
        cout << "\n";//---------------------------------------------------------- onto next line 
    } 
    return 0;
}